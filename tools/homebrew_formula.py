#!/usr/bin/env python3
"""Render the Homebrew formula of the public dev-platform CLI from a release identity record (deterministic).

  python3 tools/homebrew_formula.py --identity releases/0.9.0/identity.json [--out dev-platform.rb]
  python3 tools/homebrew_formula.py --identity releases/0.9.0/identity.json --check Formula/dev-platform.rb
  python3 tools/homebrew_formula.py --version V --archive-sha256 A --tree-sha256 T [--url file:///...]  # CI tests

The formula is a pure function of the release identity: the URL of the immutable GitHub release asset, its
archive sha256 (what Homebrew checks on download) and the tree digest pin (what the formula's test requires
of the installed tree). A matching checksum shows the bytes are the ones named; it does not establish who built
them: provenance stays with the trusted installer and the release's attestations (docs/homebrew.md, ADR 0022).
The formula installs the CLI only; it names no private repository, configuration or credential.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = "syncom-systems/dev-platform"
PYTHON = "python@3.14"  # the interpreter series of the release profile; the CLI needs >= 3.11, stdlib only
_VER = re.compile(r"^\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$")
_SHA = re.compile(r"^[0-9a-f]{64}$")
_REV = re.compile(r"^[0-9a-f]{40}$")

TEMPLATE = """\
# SPDX-License-Identifier: MIT
# Generated by tools/homebrew_formula.py in {repo} from the release identity of v{version}{revision_note}.
# sha256 is the archive digest the release's independent verification recorded; the test requires the
# installed tree to equal the release's tree digest pin. Neither replaces provenance verification by the
# trusted installer (docs/homebrew.md). Do not edit by hand.
class DevPlatform < Formula
  desc "Deterministic development control plane: CLI and verifying launcher"
  homepage "https://github.com/{repo}"
  url "{url}"
  sha256 "{archive_sha256}"
  license "MIT"

  depends_on "gh"
  depends_on "{python}"

  def install
    # The release tree byte for byte (src/, release.json, sbom.cdx.json): its digest is the release's pin.
    libexec.install "src", "release.json", "sbom.cdx.json"
    (bin/"dev-platform").write <<~EOS
      #!#{{formula_opt_bin("{python}")}}/python{python_series} -I
      import sys
      sys.dont_write_bytecode = True
      sys.path.insert(0, "#{{libexec}}/src")
      from dev_platform.cli import main
      sys.exit(main())
    EOS
    chmod 0755, bin/"dev-platform"
  end

  def caveats
    <<~EOS
      This is the dev-platform CLI and launcher only. A project's committed pins
      (dev-platform.toml, dev-platform.release-pins.json) select its platform release:
        dev-platform setup
      installs exactly that release with its own pinned trusted installer (release
      attestations are verified with gh: run `gh auth login` once), provisions its
      toolchains and runs its doctor. A verified-but-unaccepted release is used only
      with --allow-unaccepted, a decision for the project. `brew upgrade` changes this
      CLI only; project pins, installed releases and CI are unaffected.
    EOS
  end

  test do
    assert_match "dev-platform #{{version}}", shell_output("#{{bin}}/dev-platform --version")
    tree = shell_output("#{{bin}}/dev-platform digest #{{libexec}}").strip
    assert_equal "{tree_sha256}", tree
    output = shell_output("#{{bin}}/dev-platform setup --project #{{testpath}} --home #{{testpath}}/h --dry-run", 2)
    assert_match "no dev-platform.toml", output
  end
end
"""


class Invalid(Exception):
    pass


def release_url(version: str) -> str:
    return f"https://github.com/{REPO}/releases/download/v{version}/dev-platform-{version}.tar.gz"


def render(
    version: str, archive_sha256: str, tree_sha256: str, url: str | None = None, revision: str | None = None
) -> str:
    problems = []
    if not _VER.match(version or ""):
        problems.append(f"version {version!r}")
    for name, value in (("archive sha256", archive_sha256), ("tree sha256", tree_sha256)):
        if not _SHA.match(value or ""):
            problems.append(f"{name} {value!r}")
    if revision is not None and not _REV.match(revision):
        problems.append(f"source revision {revision!r}")
    url = url or release_url(version)
    # Homebrew takes the version from the archive name; only the release asset or a local test archive
    if not (url.startswith(("https://", "file:///")) and url.endswith(f"/dev-platform-{version}.tar.gz")):
        problems.append(f"url {url!r} (https:// or file:///, ending /dev-platform-{version}.tar.gz)")
    if problems:
        raise Invalid("malformed " + "; ".join(problems))
    return TEMPLATE.format(
        repo=REPO,
        version=version,
        revision_note=f" (source revision {revision})" if revision else "",
        url=url,
        archive_sha256=archive_sha256,
        tree_sha256=tree_sha256,
        python=PYTHON,
        python_series=PYTHON.split("@")[1],
    )


def from_identity(path: Path) -> str:
    ident = json.loads(Path(path).read_text())
    if ident.get("archive") != f"dev-platform-{ident.get('version')}.tar.gz":
        raise Invalid(f"{path}: archive name does not match the version")
    return render(ident["version"], ident["archive_sha256"], ident["tree_digest_pin"],
                  revision=ident.get("source_revision"))  # fmt: skip


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--identity", type=Path, help="releases/<version>/identity.json")
    ap.add_argument("--version")
    ap.add_argument("--archive-sha256")
    ap.add_argument("--tree-sha256")
    ap.add_argument("--url", help="default: the GitHub release asset of --version")
    out = ap.add_mutually_exclusive_group()
    out.add_argument("--out", type=Path)
    out.add_argument("--check", type=Path, help="exit 1 unless this file equals the rendering")
    a = ap.parse_args(argv)
    try:
        if a.identity:
            if a.version or a.archive_sha256 or a.tree_sha256 or a.url:
                raise Invalid("--identity excludes --version/--archive-sha256/--tree-sha256/--url")
            text = from_identity(a.identity)
        else:
            text = render(a.version, a.archive_sha256, a.tree_sha256, a.url)
    except (Invalid, OSError, KeyError, json.JSONDecodeError) as e:
        print(f"homebrew_formula: {e}", file=sys.stderr)
        return 2
    if a.check:
        same = a.check.is_file() and a.check.read_text() == text
        print(f"{a.check}: " + ("equals the rendering" if same else "DIFFERS from the rendering"))
        return 0 if same else 1
    if a.out:
        a.out.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
