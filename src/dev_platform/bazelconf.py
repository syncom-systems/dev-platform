"""Bazel configuration owned by the platform release (`profile.bazel`).

A project selects a pinned release and a toolchain profile; it does not choose compiler, runtime, formatter,
linter or type-checker versions or their policy. For a profile that carries a `bazel` section this module
renders, from the release alone, the files Bazel and its language rules need:

  dev-platform/toolchains.MODULE.bazel   rules_rust / rules_python, toolchain versions, pinned hashes
  dev-platform/bazel.bazelrc             formatter, lint and coverage policy (`--config=dp-lint`)
  dev-platform/{BUILD.bazel,*.bzl,...}   rules the policy needs (pytest test rule, lint aspect, Rust macro)
  dev-platform/python_lock.txt           hash-locked pytest, coverage and mypy
  rustfmt.toml clippy.toml ruff.toml mypy.ini   tool policy, at the root where editors and CLIs look for it
                                                  and in dev-platform/ where Bazel consumes it
  dev-platform/generated.json            release, profile and sha256 of every generated file

Every number in the rendering (versions, urls, hashes) comes from the toolchain manifest; the policy files are
static files of this release. `materialize` writes the files; it refuses to overwrite a file the platform did
not generate and never edits or deletes project-owned files (`--add-hooks` appends the two entry lines).
`check` is what conformance runs: it fails on a missing, edited or foreign generated file and on independently
maintained settings that conflict with the platform's (a second rules_rust, a pinned compiler, another
`ruff.toml`, ...), each with the action that resolves it. Nothing here executes a tool.
"""

from __future__ import annotations

import configparser
import hashlib
import json
import os
import re
import tomllib
from pathlib import Path

from dev_platform.errors import ConfigError

SCHEMA = "dev-platform.generated/v1"
OUT_DIR = "dev-platform"
MARK = "# generated by dev-platform "
TEMPLATES = Path(__file__).resolve().parent / "bazel"
MODULE_HOOK = f'include("//{OUT_DIR}:toolchains.MODULE.bazel")'
BAZELRC_HOOK = f"import %workspace%/{OUT_DIR}/bazel.bazelrc"
EDITIONS = ("2015", "2018", "2021", "2024")
# manifest platform key -> Rust/rules_python triple, Bazel constraints
PLATFORMS = {
    "darwin-arm64": {"triple": "aarch64-apple-darwin", "os": "macos", "cpu": "aarch64"},
    "linux-x86_64": {"triple": "x86_64-unknown-linux-gnu", "os": "linux", "cpu": "x86_64"},
}
RUST_POLICY = ("rustfmt.toml", "clippy.toml")
PYTHON_POLICY = ("ruff.toml", "mypy.ini")
_PRUNE = {".git", ".devenv", "node_modules", "target", ".venv", "venv", ".tox", "__pycache__", OUT_DIR}
_STRAY = {  # file name -> languages it configures
    "rustfmt.toml": "rust",
    ".rustfmt.toml": "rust",
    "clippy.toml": "rust",
    ".clippy.toml": "rust",
    "rust-toolchain": "rust",
    "rust-toolchain.toml": "rust",
    "ruff.toml": "python",
    ".ruff.toml": "python",
    "mypy.ini": "python",
    ".mypy.ini": "python",
    "pytest.ini": "python",
    ".coveragerc": "python",
    ".python-version": "python",
}
_TOOL_VERSIONS_KEYS = {
    "rust": "rust",
    "python": "python",
    "ruff": "python",
    "bazel": "any",
    "bazelisk": "any",
}
_INI_SECTIONS = ("mypy", "tool:pytest", "coverage:run", "coverage:report", "coverage:paths")
_PYPROJECT_TABLES = ("ruff", "mypy", "pytest", "coverage")


def languages(profile: dict) -> set[str]:
    tools = profile.get("tools", {})
    return ({"rust"} if "rust-toolchain" in tools else set()) | (
        {"python"} if "python-runtime" in tools else set()
    )


def _module_version(tool: dict, name: str) -> str:
    for ent in tool.get("integrity", []):
        if ent.get("kind") == "bazel_module" and ent.get("name") == name:
            return ent["version"]
    raise ConfigError([f"{name}: the tool's integrity must pin the {name} module"])


def validate_profile(manifest: dict, pname: str) -> list[str]:
    """Problems that stop a profile's `bazel` section from being rendered (empty when it can be)."""
    prof = manifest["profiles"][pname]
    cfg, tools, errs = prof.get("bazel"), prof["tools"], []
    w = f"profile {pname}.bazel"
    if not isinstance(cfg, dict):
        return [f"{w}: object required"]
    langs = languages(prof)
    if not langs:
        errs.append(f"{w}: needs a rust-toolchain and/or python-runtime Bazel-managed tool")
    for need in ("bazel", "bazelisk"):
        if need not in tools:
            errs.append(f"{w}: tool {need} required")
    if "rust" in langs:
        if cfg.get("edition") not in EDITIONS:
            errs.append(f"{w}.edition: one of {list(EDITIONS)}")
        errs += _need_sources(w, tools, "rust-dev", "rust-components")
        try:
            _module_version(tools["rust-toolchain"], "rules_rust")
        except ConfigError as e:
            errs += e.problems
        if tools.get("rust-dev", {}).get("version") != tools["rust-toolchain"]["version"]:
            errs.append(f"{w}: rust-dev and rust-toolchain must be the same version")
    if "python" in langs:
        errs += _need_sources(w, tools, "python") + _need_sources(w, tools, "ruff")
        try:
            _module_version(tools["python-runtime"], "rules_python")
        except ConfigError as e:
            errs += e.problems
        if tools.get("python", {}).get("version") != tools["python-runtime"]["version"]:
            errs.append(f"{w}: python and python-runtime must be the same version")
        for t in ("pytest", "pytest-cov", "coverage", "mypy"):
            if t not in tools or tools[t].get("bound_to") != "bazel-config":
                errs.append(f"{w}: tool {t} must be Bazel-managed and bound_to bazel-config")
    return errs


def _need_sources(w: str, tools: dict, name: str, kind: str | None = None) -> list[str]:
    spec = tools.get(name)
    if not spec:
        return [f"{w}: tool {name} required"]
    errs = []
    for key in PLATFORMS:
        src = (spec.get("source") or {}).get(key)
        if not src:
            errs.append(f"{w}: tool {name} needs a source for {key}")
        elif kind and src.get("type") != kind:
            errs.append(f"{w}: tool {name} source for {key} must be of type {kind}")
    return errs


def _template(name: str) -> str:
    return (TEMPLATES / name).read_text()


def _sub(text: str, **values: str) -> str:
    for k, v in values.items():
        text = text.replace(f"@@{k}@@", v)
    left = re.findall(r"@@[A-Z_0-9]+@@", text)
    if left:
        raise ConfigError([f"template placeholder(s) left unfilled: {sorted(set(left))}"])
    return text


def _starlark_dict(entries: dict[str, str], indent: int = 8) -> str:
    pad = " " * indent
    return "\n".join(f'{pad}"{k}": "{entries[k]}",' for k in sorted(entries))


def rust_sha256s(rust_dev: dict) -> dict[str, str]:
    """Archive name -> sha256 for every component archive the Rust toolchain declaration may fetch."""
    out: dict[str, str] = {}
    for key in sorted(rust_dev["source"]):
        if key not in PLATFORMS:
            continue
        for c in rust_dev["source"][key]["components"]:
            if out.setdefault(c["archive"], c["sha256"]) != c["sha256"]:
                raise ConfigError([f"rust-dev: archive {c['archive']} is pinned to two different hashes"])
    return out


def _python_overrides(python: dict) -> str:
    blocks = []
    for key in sorted(PLATFORMS):
        src = python["source"][key]
        blocks.append(
            "python.single_version_platform_override(\n"
            f'    platform = "{PLATFORMS[key]["triple"]}",\n'
            f'    python_version = "{python["version"]}",\n'
            f'    sha256 = "{src["sha256"]}",\n'
            f'    strip_prefix = "{src.get("strip", "python")}",\n'
            f'    urls = ["{src["url"]}"],\n'
            ")"
        )
    return "\n".join(blocks)


def _ruff_archives(ruff: dict) -> str:
    blocks = []
    for key in sorted(PLATFORMS):
        src = ruff["source"][key]
        blocks.append(
            "http_archive(\n"
            f'    name = "dp_ruff_{key.replace("-", "_")}",\n'
            '    build_file_content = """load("@bazel_skylib//rules:native_binary.bzl", "native_binary")\n'
            'native_binary(name = "ruff_bin", src = "ruff", out = "ruff_exe",'
            ' visibility = ["//visibility:public"])\n'
            '""",\n'
            f'    sha256 = "{src["sha256"]}",\n'
            f'    strip_prefix = "{src.get("strip", "")}",\n'
            f'    urls = ["{src["url"]}"],\n'
            ")"
        )
    return "\n".join(blocks)


def _ruff_select() -> str:
    return "\n".join(
        f'        ":host_{key.replace("-", "_")}": "@dp_ruff_{key.replace("-", "_")}//:ruff_bin",'
        for key in sorted(PLATFORMS)
    )


def _host_settings() -> str:
    return "\n".join(
        f'\nconfig_setting(\n    name = "host_{key.replace("-", "_")}",\n'
        f'    constraint_values = ["@platforms//os:{p["os"]}", "@platforms//cpu:{p["cpu"]}"],\n)'
        for key, p in sorted(PLATFORMS.items())
    )


def render(manifest: dict, profile: str, version: str) -> dict[str, str]:
    """Relative path -> text of every file the release generates for `profile`, deterministically."""
    prof = manifest["profiles"][profile]
    problems = validate_profile(manifest, profile)
    if problems:
        raise ConfigError(problems)
    langs, tools = languages(prof), prof["tools"]
    head = f"{MARK}{version} for profile {profile}; do not edit (edits fail conformance)\n"
    out: dict[str, str] = {}
    rust_version = tools["rust-toolchain"]["version"] if "rust" in langs else ""
    edition = prof["bazel"].get("edition", "")

    def put(path: str, text: str) -> None:
        out[path] = head + text

    module = _template("module.base.bazel")
    rc = _template("bazelrc.base")
    exports = ["BUILD.bazel"]
    if "rust" in langs:
        module += _sub(
            _template("module.rust.bazel"),
            RULES_RUST=_module_version(tools["rust-toolchain"], "rules_rust"),
            EDITION=edition,
            RUST_VERSION=rust_version,
            RUST_SHA256S=_starlark_dict(rust_sha256s(tools["rust-dev"])),
        )
        rc += _template("bazelrc.rust")
        for name in RUST_POLICY:
            text = _sub(_template(name), RUST_VERSION=rust_version, EDITION=edition)
            put(name, text)
            put(f"{OUT_DIR}/{name}", text)
            exports.append(name)
        put(f"{OUT_DIR}/rust.bzl", _sub(_template("rust.bzl"), EDITION=edition))
        exports.append("rust.bzl")
    if "python" in langs:
        module += _sub(
            _template("module.python.bazel"),
            RULES_PYTHON=_module_version(tools["python-runtime"], "rules_python"),
            PYTHON_VERSION=tools["python"]["version"],
            PYTHON_OVERRIDES=_python_overrides(tools["python"]),
            RUFF_ARCHIVES=_ruff_archives(tools["ruff"]),
        )
        rc += _template("bazelrc.python")
        for name in PYTHON_POLICY:
            text = _template(name)
            put(name, text)
            put(f"{OUT_DIR}/{name}", text)
            exports.append(name)
        for name in ("lint.bzl", "python.bzl", "coveragerc", "python_lock.txt"):
            put(f"{OUT_DIR}/{name}", _template(name))
            exports.append(name)
        for name in ("pytest_main.py", "mypy_main.py"):
            put(f"{OUT_DIR}/{name}", _template(name + ".tmpl"))
            exports.append(name)
    groups = (["rustfmt_checks", "clippy_checks"] if "rust" in langs else []) + (
        ["dp_py_checks"] if "python" in langs else []
    )
    rc += f"build:dp-lint --output_groups={','.join(groups)}\n"
    build = _sub(_template("BUILD.base.bazel"), EXPORTS=json.dumps(sorted(exports)))
    if "python" in langs:
        build += _sub(_template("BUILD.python.bazel"), RUFF_SELECT=_ruff_select())
        build += _host_settings() + "\n"
    put(f"{OUT_DIR}/BUILD.bazel", build)
    put(f"{OUT_DIR}/toolchains.MODULE.bazel", module)
    put(f"{OUT_DIR}/bazel.bazelrc", rc)
    record = {
        "schema": SCHEMA,
        "release": version,
        "profile": profile,
        "files": {p: hashlib.sha256(t.encode()).hexdigest() for p, t in sorted(out.items())},
    }
    out[f"{OUT_DIR}/generated.json"] = json.dumps(record, indent=2, sort_keys=True) + "\n"
    return dict(sorted(out.items()))


def digest(files: dict[str, str]) -> str:
    h = hashlib.sha256()
    for p in sorted(files):
        h.update(f"{p}\0{hashlib.sha256(files[p].encode()).hexdigest()}\n".encode())
    return h.hexdigest()


def _ours(text: str) -> bool:
    if text.startswith(MARK):
        return True
    try:
        return json.loads(text).get("schema") == SCHEMA
    except (ValueError, AttributeError):
        return False


def _read(path: Path) -> str | None:
    try:
        return path.read_text()
    except (OSError, UnicodeDecodeError):
        return None


def _conflict(kind: str, path: str, detail: str, action: str) -> dict:
    return {"kind": kind, "path": path, "detail": detail, "action": action}


def _code_lines(text: str) -> str:
    return "\n".join(line.split("#", 1)[0] for line in text.splitlines())


def _walk(root: Path):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in _PRUNE and not d.startswith("bazel-"))
        for name in sorted(filenames):
            yield Path(dirpath) / name


def _generated_conflicts(root: Path, want: dict[str, str]) -> list[dict]:
    out = []
    absent = [rel for rel in want if not (root / rel).exists()]
    if len(absent) == len(want):
        return [
            _conflict(
                "missing",
                OUT_DIR + "/",
                f"the platform's Bazel configuration is not materialized ({len(want)} files)",
                "run: dev-platform toolchain materialize --add-hooks",
            )
        ]
    for rel, text in want.items():
        have = _read(root / rel)
        if have is None:
            if rel in absent:
                out.append(
                    _conflict("missing", rel, "not materialized", "run: dev-platform toolchain materialize")
                )
            else:
                out.append(_conflict("foreign", rel, "not readable as text", "remove it, then materialize"))
        elif have != text:
            if _ours(have):
                out.append(
                    _conflict(
                        "stale",
                        rel,
                        "differs from this release's rendering (edited, or generated by another release)",
                        "run: dev-platform toolchain materialize",
                    )
                )
            else:
                out.append(
                    _conflict(
                        "foreign",
                        rel,
                        "exists but was not generated by the platform; the platform owns this setting",
                        "remove it or move its intent into the platform release; it is never overwritten",
                    )
                )
    d = root / OUT_DIR
    if d.is_dir():
        for p in sorted(x for x in d.rglob("*") if x.is_file()):
            rel = p.relative_to(root).as_posix()
            if rel not in want:
                out.append(
                    _conflict(
                        "unexpected",
                        rel,
                        f"{OUT_DIR}/ is platform-owned and this release does not generate this file",
                        "remove it or keep your own files outside " + OUT_DIR + "/",
                    )
                )
    return out


def _hook_conflicts(root: Path) -> list[dict]:
    out = []
    for rel, line in (("MODULE.bazel", MODULE_HOOK), (".bazelrc", BAZELRC_HOOK)):
        text = _read(root / rel)
        if text is None or line not in [x.strip() for x in _code_lines(text).splitlines()]:
            out.append(
                _conflict(
                    "hook",
                    rel,
                    "does not load the platform configuration" if text is not None else "missing",
                    f"add the line: {line}  (or run: dev-platform toolchain materialize --add-hooks)",
                )
            )
    return out


_OWNED = "remove it; the platform declares it"
_RUST_DECLARATIONS = (
    (r'bazel_dep\(\s*name\s*=\s*"rules_rust"', "declares rules_rust", _OWNED),
    (r'use_extension\(\s*"@rules_rust//rust:extensions\.bzl"', "configures the Rust toolchain", _OWNED),
    (r'_override\(\s*module_name\s*=\s*"rules_rust"', "overrides rules_rust", "remove the override"),
    (r"register_toolchains\([^)]*@rust_toolchains", "registers a Rust toolchain", _OWNED),
)
_PYTHON_DECLARATIONS = (
    (r'bazel_dep\(\s*name\s*=\s*"rules_python"', "declares rules_python", _OWNED),
    (
        r'use_extension\(\s*"@rules_python//python/extensions:python\.bzl"',
        "configures the Python toolchain",
        _OWNED,
    ),
    (r'_override\(\s*module_name\s*=\s*"rules_python"', "overrides rules_python", "remove the override"),
    (r"register_toolchains\([^)]*@(python_|pythons_hub)", "registers a Python toolchain", _OWNED),
    (r'hub_name\s*=\s*"dp_pytools"', "redefines the platform's Python tool hub", "choose another hub name"),
)


def _module_conflicts(root: Path, langs: set[str], python_version: str) -> list[dict]:
    out = []
    checks = (_RUST_DECLARATIONS if "rust" in langs else ()) + (
        _PYTHON_DECLARATIONS if "python" in langs else ()
    )
    for p in _walk(root):
        if p.name != "MODULE.bazel" and not p.name.endswith(".MODULE.bazel"):
            continue
        rel = p.relative_to(root).as_posix()
        text = _code_lines(_read(p) or "")
        for pat, what, action in checks:
            if re.search(pat, text):
                out.append(_conflict("independent-declaration", rel, what, action))
        if "python" in langs:
            for m in re.finditer(r'python_version\s*=\s*"([^"]+)"', text):
                if m.group(1) != python_version:
                    out.append(
                        _conflict(
                            "independent-declaration",
                            rel,
                            f"python_version {m.group(1)} differs from the platform's {python_version}",
                            f"use {python_version} or remove the declaration",
                        )
                    )
    return out


def _bazelrc_conflicts(root: Path, langs: set[str], bazel_version: str) -> list[dict]:
    pats = [(r"--extra_toolchains", "registers toolchains outside the platform's selection")]
    if "rust" in langs:
        pats.append((r"@rules_rust//rust/settings", "sets a rules_rust setting the platform owns"))
    if "python" in langs:
        pats.append((r"@rules_python//python[^\s]*python_version", "selects a Python version"))
    out = []
    for p in _walk(root):
        if p.name != ".bazelrc" and not p.name.endswith(".bazelrc"):
            continue
        text = _code_lines(_read(p) or "")
        for pat, what in pats:
            if re.search(pat, text):
                out.append(
                    _conflict("independent-setting", p.relative_to(root).as_posix(), what, "remove the flag")
                )
    rc = _read(root / ".bazeliskrc")
    m = re.search(r"^\s*USE_BAZEL_VERSION\s*=\s*(\S+)", rc or "", re.M)
    if m and m.group(1) != bazel_version:
        out.append(
            _conflict(
                "independent-setting",
                ".bazeliskrc",
                f"USE_BAZEL_VERSION {m.group(1)} differs from the platform's {bazel_version}",
                "remove it; the Bazel version comes from .bazelversion",
            )
        )
    return out


def _tool_config_conflicts(root: Path, langs: set[str], want: dict[str, str]) -> list[dict]:
    out = []
    for p in _walk(root):
        rel = p.relative_to(root).as_posix()
        lang = _STRAY.get(p.name)
        if rel in want:
            continue  # a generated file: judged by _generated_conflicts
        if lang in langs:
            out.append(
                _conflict(
                    "tool-config",
                    rel,
                    f"{p.name} configures a tool whose policy the platform owns",
                    "remove it; the platform release carries the policy",
                )
            )
        elif p.name == ".tool-versions":
            for line in (_read(p) or "").splitlines():
                key = line.split("#", 1)[0].split()[:1]
                if key and _TOOL_VERSIONS_KEYS.get(key[0]) in (*langs, "any"):
                    out.append(
                        _conflict(
                            "tool-config",
                            rel,
                            f"{key[0]} version is pinned outside the platform",
                            f"remove the {key[0]} line",
                        )
                    )
        elif p.name == "pyproject.toml" and "python" in langs:
            try:
                doc = tomllib.loads(p.read_text())
            except (OSError, ValueError):
                continue
            tools = doc.get("tool", {})
            for t in _PYPROJECT_TABLES:
                if t in tools:
                    out.append(
                        _conflict(
                            "tool-config",
                            rel,
                            f"[tool.{t}] configures a tool whose policy the platform owns",
                            f"remove [tool.{t}]",
                        )
                    )
        elif p.name in ("setup.cfg", "tox.ini") and "python" in langs:
            cp = configparser.ConfigParser(interpolation=None, strict=False)
            try:
                cp.read_string(p.read_text())
            except (OSError, configparser.Error, UnicodeDecodeError):
                continue
            for s in _INI_SECTIONS:
                if cp.has_section(s):
                    out.append(
                        _conflict(
                            "tool-config",
                            rel,
                            f"[{s}] configures a tool whose policy the platform owns",
                            f"remove [{s}]",
                        )
                    )
    return out


def check(manifest: dict, profile: str, root: Path, version: str) -> dict:
    """The conformance verdict for a project's Bazel configuration against this release (reads only)."""
    root = Path(root)
    prof = manifest["profiles"][profile]
    want = render(manifest, profile, version)
    langs, tools = languages(prof), prof["tools"]
    conflicts = _generated_conflicts(root, want) + _hook_conflicts(root)
    py = tools["python"]["version"] if "python" in langs else ""
    conflicts += _module_conflicts(root, langs, py)
    conflicts += _bazelrc_conflicts(root, langs, tools["bazel"]["version"])
    conflicts += _tool_config_conflicts(root, langs, want)
    dig = digest(want)
    return {
        "status": "ok" if not conflicts else "mismatch",
        "profile": profile,
        "release": version,
        "digest": dig,
        "files": sorted(want),
        "conflicts": conflicts,
    }


def materialize(
    manifest: dict,
    profile: str,
    root: Path,
    version: str,
    *,
    add_hooks: bool = False,
    create_hooks: bool = False,
    dry_run: bool = False,
) -> dict:
    """Write the generated files. Atomic in effect: nothing is written when any target is a foreign file.
    `add_hooks` appends the entry lines to project files; `create_hooks` only writes them into files that do
    not exist yet, so an existing project-owned file is never touched (its missing line is reported by
    `check`)."""
    root = Path(root)
    want = render(manifest, profile, version)
    foreign = [c for c in _generated_conflicts(root, want) if c["kind"] == "foreign"]
    report: dict = {
        "profile": profile,
        "release": version,
        "written": [],
        "unchanged": [],
        "added_hooks": [],
        "refused": foreign,
    }
    if foreign:
        return report
    for rel, text in want.items():
        target = root / rel
        if target.is_file() and target.read_text() == text:
            report["unchanged"].append(rel)
            continue
        report["written"].append(rel)
        if not dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
    # Files that were generated for another release of this profile and are no longer rendered belong to the
    # platform: they are reported by `check` as unexpected, never deleted here.
    if add_hooks or create_hooks:
        for rel, line in (("MODULE.bazel", MODULE_HOOK), (".bazelrc", BAZELRC_HOOK)):
            target = root / rel
            text = _read(target)
            if create_hooks and not add_hooks and text is not None:
                continue
            if text is not None and line in [x.strip() for x in _code_lines(text).splitlines()]:
                continue
            report["added_hooks"].append(rel)
            if dry_run:
                continue
            if text is None:
                head = (
                    f'module(name = "{re.sub(r"[^a-z0-9_.-]", "_", root.resolve().name.lower())}")\n'
                    if rel == "MODULE.bazel"
                    else ""
                )
                target.write_text(head + line + "\n")
            else:
                target.write_text(text + ("" if text.endswith("\n") or not text else "\n") + line + "\n")
    bv = root / ".bazelversion"
    if not bv.exists() and not dry_run:
        bv.write_text(manifest["profiles"][profile]["tools"]["bazel"]["version"] + "\n")
        report["written"].append(".bazelversion")
    return report
